import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { prisma } from '../lib/prisma';
import { AuthService, hashPassword, SESSION_IDLE_MS } from '../services/auth.service';
import { AlunoService } from '../services/aluno.service';
import { autorizarDocente, autorizarLeituraAluno } from '../services/acesso.service';
import { createApp } from '../app';
import { once } from 'node:events';
import type { AddressInfo } from 'node:net';
const enabled = process.env.RUN_DATABASE_TESTS === '1';
test('PostgreSQL: cadastro, hash, sessão, expiração e restrições acadêmicas', { skip: !enabled }, async () => {
 const address = new URL(process.env.DATABASE_URL ?? '');
 if (!decodeURIComponent(address.pathname).endsWith('_test') || !['127.0.0.1','localhost'].includes(address.hostname)) throw new Error('Testes exigem banco local com nome terminado em _test.');
 const suffix = randomUUID();
 const ids: { users: string[]; turmas: string[]; disciplinas: string[]; periodos: string[]; vinculos: string[]; atividades: string[]; matriculas: string[] } = { users: [], turmas: [], disciplinas: [], periodos: [], vinculos: [], atividades: [], matriculas: [] };
 try {
  const coord = await prisma.usuario.create({ data: { nome: 'Teste', email: suffix + '@example.test', senha: await hashPassword('Senha-teste-segura-123'), role: 'COORDENADOR', coordenador: { create: {} } } }); ids.users.push(coord.id);
  const service = new AlunoService();
  const student = await service.criarAluno({ nome: 'Aluno teste', email: 'aluno-' + suffix + '@example.test', senha: 'Senha-teste-segura-123' }, coord.id); ids.users.push(student.usuario.id);
  assert.equal('senha' in student.usuario, false);
  const stored = await prisma.usuario.findUniqueOrThrow({ where: { id: student.usuario.id } });
  const app = createApp({ origin: 'http://localhost:5173' });
  const server = app.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const url = 'http://127.0.0.1:' + (server.address() as AddressInfo).port;
  try {
   const login = await fetch(url + '/api/auth/login', { method: 'POST', headers: { origin: 'http://localhost:5173', 'content-type': 'application/json' }, body: JSON.stringify({ email: coord.email, senha: 'Senha-teste-segura-123' }) });
   assert.equal(login.status, 200);
   const cookie = login.headers.get('set-cookie')!.split(';')[0];
   const sessionBody = await login.json() as { dados: { csrfToken: string } };
   const headers = { origin: 'http://localhost:5173', 'content-type': 'application/json', cookie, 'x-csrf-token': sessionBody.dados.csrfToken };
   const created = await fetch(url + '/api/alunos', { method: 'POST', headers, body: JSON.stringify({ nome: 'Aluno HTTP', email: 'http-' + suffix + '@example.test', senha: 'Senha-teste-segura-123' }) });
   assert.equal(created.status, 201);
   const dto = await created.json() as { dados: { usuario: { id: string } } };
   ids.users.push(dto.dados.usuario.id);
   assert.doesNotMatch(JSON.stringify(dto), /"senha"/);
   const list = await fetch(url + '/api/alunos', { headers });
   assert.equal(list.status, 200); assert.doesNotMatch(await list.text(), /"senha"/);
   const forbiddenRole = await fetch(url + '/api/alunos', { method: 'POST', headers, body: JSON.stringify({ nome: 'Outro', email: 'x@example.test', senha: 'Senha-teste-segura-123', role: 'COORDENADOR' }) });
   assert.equal(forbiddenRole.status, 400);
   assert.equal((await fetch(url + '/api/auth/logout', { method: 'POST', headers })).status, 204);
   assert.equal((await fetch(url + '/api/auth/me', { headers })).status, 401);
  } finally {
   server.closeAllConnections(); await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
  }
  await assert.rejects(() => prisma.professor.create({ data: { usuarioId: stored.id } }));
  assert.notEqual(stored.senha, 'Senha-teste-segura-123'); assert.equal(stored.role, 'ALUNO');
  await assert.rejects(() => service.criarAluno({ nome: 'Outro', email: stored.email, senha: 'Senha-teste-segura-123' }, coord.id));
  await assert.rejects(() => service.criarAluno({ nome: 'Outro', email: 'b@example.test', senha: 'Senha-teste-segura-123', role: 'COORDENADOR' }, coord.id));
  const auth = new AuthService();
  await assert.rejects(() => auth.entrar({ email: stored.email, senha: 'senha-errada' }));
  const session = await auth.entrar({ email: stored.email, senha: 'Senha-teste-segura-123' });
  assert.equal((await auth.autenticar(session.token)).usuario.id, stored.id);
  await auth.sair(session.token); await assert.rejects(() => auth.autenticar(session.token));
  const idle = await auth.entrar({ email: stored.email, senha: 'Senha-teste-segura-123' });
  await prisma.sessao.updateMany({ where: { usuarioId: stored.id }, data: { ultimaAtividade: new Date(Date.now() - SESSION_IDLE_MS - 1000) } });
  await assert.rejects(() => auth.autenticar(idle.token));
  const expired = await auth.entrar({ email: stored.email, senha: 'Senha-teste-segura-123' });
  await prisma.sessao.updateMany({ where: { usuarioId: stored.id }, data: { expiraEm: new Date(0) } });
  await assert.rejects(() => auth.autenticar(expired.token));
  const parent = await prisma.usuario.create({ data: { nome: 'Responsável teste', email: 'resp-' + suffix + '@example.test', senha: stored.senha, role: 'RESPONSAVEL', responsavel: { create: {} } }, include: { responsavel: true } }); ids.users.push(parent.id);
  const parentSession = await auth.entrar({ email: parent.email, senha: 'Senha-teste-segura-123' });
  const parentContext = (await auth.autenticar(parentSession.token)).usuario;
  await assert.rejects(() => autorizarLeituraAluno(parentContext, student.id));
  const link = await prisma.alunoResponsavel.create({ data: { alunoId: student.id, responsavelId: parent.responsavel!.id, validadoPorId: coord.id } });
  await autorizarLeituraAluno(parentContext, student.id);
  await assert.rejects(() => autorizarLeituraAluno(parentContext, randomUUID()));
  await prisma.alunoResponsavel.update({ where: { id: link.id }, data: { fim: new Date(Date.now() + 1) } });
  await assert.rejects(() => autorizarLeituraAluno(parentContext, student.id, new Date(Date.now() + 1000)));
  const turma = await prisma.turma.create({ data: { nome: 'Turma-' + suffix, anoLetivo: 2026 } }); ids.turmas.push(turma.id);
  const turma2 = await prisma.turma.create({ data: { nome: 'Outra-' + suffix, anoLetivo: 2026 } }); ids.turmas.push(turma2.id);
  const matricula = await prisma.alunoTurma.create({ data: { alunoId: student.id, turmaId: turma.id, anoLetivo: 2026, inicio: new Date('2026-01-01') } }); ids.matriculas.push(matricula.id);
  await assert.rejects(() => prisma.alunoTurma.create({ data: { alunoId: student.id, turmaId: turma2.id, anoLetivo: 2026, inicio: new Date('2026-02-01') } }));
  const prof = await prisma.usuario.create({ data: { nome: 'Professor teste', email: 'prof-' + suffix + '@example.test', senha: stored.senha, role: 'PROFESSOR', professor: { create: {} } }, include: { professor: true } }); ids.users.push(prof.id);
  const periodo = await prisma.periodoLetivo.create({ data: { nome: suffix, anoLetivo: 2026, inicio: new Date('2026-01-01'), fim: new Date('2027-01-01') } }); ids.periodos.push(periodo.id);
  for (const nome of ['Mat-', 'Fis-']) {
   const disciplina = await prisma.disciplina.create({ data: { nome: nome + suffix } }); ids.disciplinas.push(disciplina.id);
   const vinculo = await prisma.professorTurma.create({ data: { professorId: prof.professor!.id, turmaId: turma.id, anoLetivo: 2026, disciplinaId: disciplina.id, inicio: new Date('2026-01-01') } }); ids.vinculos.push(vinculo.id);
  }
  assert.equal(ids.vinculos.length, 2);
  const profSession = await auth.entrar({ email: prof.email, senha: 'Senha-teste-segura-123' });
  const profContext = (await auth.autenticar(profSession.token)).usuario;
  await autorizarDocente(profContext, ids.vinculos[0]);
  await assert.rejects(() => autorizarDocente(profContext, randomUUID()));
  const atividade = await prisma.atividade.create({ data: { titulo: 'Prova', dataAvaliacao: new Date('2026-06-01'), periodoId: periodo.id, anoLetivo: 2026, vinculoDocenteId: ids.vinculos[0] } }); ids.atividades.push(atividade.id);
  const nota = await prisma.nota.create({ data: { atividadeId: atividade.id, matriculaId: matricula.id, valor: 8 } });
  const updated = await prisma.nota.updateMany({ where: { id: nota.id, versao: 1 }, data: { valor: 9, versao: { increment: 1 } } });
  assert.equal(updated.count, 1);
  const stale = await prisma.nota.updateMany({ where: { id: nota.id, versao: 1 }, data: { valor: 7, versao: { increment: 1 } } });
  assert.equal(stale.count, 0);
  await assert.rejects(() => prisma.nota.update({ where: { id: nota.id }, data: { valor: 5 } }));
  await assert.rejects(() => prisma.alunoTurma.update({ where: { id: matricula.id }, data: { fim: new Date('2026-05-01') } }));
  await assert.rejects(() => prisma.nota.create({ data: { atividadeId: atividade.id, matriculaId: matricula.id, valor: 8 } }));
  const outraAtividade = await prisma.atividade.create({ data: { titulo: 'Prova 2', dataAvaliacao: new Date('2026-06-02'), periodoId: periodo.id, anoLetivo: 2026, vinculoDocenteId: ids.vinculos[0] } }); ids.atividades.push(outraAtividade.id);
  await assert.rejects(() => prisma.nota.create({ data: { atividadeId: outraAtividade.id, matriculaId: matricula.id, valor: 11 } }));
  await prisma.periodoLetivo.update({ where: { id: periodo.id }, data: { fechado: true } });
  await assert.rejects(() => prisma.nota.create({ data: { atividadeId: outraAtividade.id, matriculaId: matricula.id, valor: 7 } }));
 } finally {
  await prisma.nota.deleteMany({ where: { atividadeId: { in: ids.atividades } } });
  await prisma.atividade.deleteMany({ where: { id: { in: ids.atividades } } });
  await prisma.professorTurma.deleteMany({ where: { id: { in: ids.vinculos } } });
  await prisma.alunoTurma.deleteMany({ where: { id: { in: ids.matriculas } } });
  await prisma.turma.deleteMany({ where: { id: { in: ids.turmas } } });
  await prisma.periodoLetivo.deleteMany({ where: { id: { in: ids.periodos } } });
  await prisma.disciplina.deleteMany({ where: { id: { in: ids.disciplinas } } });
  await prisma.auditoria.deleteMany({ where: { autorId: { in: ids.users } } });
  await prisma.alunoResponsavel.deleteMany({ where: { aluno: { usuarioId: { in: ids.users } } } });
  await prisma.aluno.deleteMany({ where: { usuarioId: { in: ids.users } } });
  await prisma.professor.deleteMany({ where: { usuarioId: { in: ids.users } } });
  await prisma.coordenador.deleteMany({ where: { usuarioId: { in: ids.users } } });
  await prisma.responsavel.deleteMany({ where: { usuarioId: { in: ids.users } } });
  await prisma.usuario.deleteMany({ where: { id: { in: ids.users } } });
  await prisma.$disconnect();
 }
});
